"""読み上げ用の文を作る（字幕の文 → 声で読ませる文）。

Open JTalk は固有名詞・英字・記号を読み間違えるため、
1) 置き換え表で読みを直し、2) カナに変換して「英字」「既知の誤読」が残っていないか点検する。
点検に引っかかったら止める（間違った読みのまま声を作らない）。
"""
import re

import pyopenjtalk

# 長いものから順に置き換える
TABLE = [
    ("e東京喰種", "イー東京グール"), ("東京喰種", "東京グール"), ("喰種チャージ", "グールチャージ"), ("喰種", "グール"),
    ("HYPER", "ハイパー"), ("RUSH", "ラッシュ"), ("LT", "エルティー"), ("ST", "エスティー"), ("AI", "エーアイ"),
    ("図柄揃い", "ズガラゾロイ"), ("出玉", "デダマ"), ("作りました", "つくりました"), ("作って", "つくって"),
    ("大きすぎ", "おおきすぎ"), ("大きい", "おおきい"), ("大きく", "おおきく"), ("気のせい", "きのせい"), ("直後", "ちょくご"),
    ("A組", "エーぐみ"), ("B組", "ビーぐみ"), ("1G連", "いちゲーレン"), ("等価交換", "とうかこうかん"), ("1日", "いちにち"), ("20日間", "はつかかん"),
    ("1万人", "いちまんにん"), ("1万回", "いちまんかい"), ("1万個", "いちまんこ"),
    ("入れた人", "はいれたひと"), ("入れなかった", "はいれなかった"),
    ("電脳アリス", "でんのうアリス"), ("回転率", "かいてんりつ"), ("損益", "そんえき"),
]
BAD = ["クエシュ", "ズガラソロイ", "ダシダマ", "ヅクリ", "アールユーエス", "エスティーエー", "レーテン", "ラッシュハ", "ノハズ"]


def fraction(m):
    """「1/95.3」→「95.3分の1」"""
    return f"{m.group(2)}分の{m.group(1)}"


def to_say(s):
    s = re.sub(r"(\d+)/(\d+(?:\.\d+)?)", fraction, s)
    s = re.sub(r"(\d)\.(\d)", r"\1点\2", s)          # 小数点は「点」に（どの読み上げソフトでもテンと読ませる）
    for a, b in TABLE:
        s = s.replace(a, b)
    s = s.replace("％", "パーセント").replace("%", "パーセント")
    s = s.replace("＋", "プラス").replace("−", "マイナス").replace("+", "プラス")
    return s


def check(say):
    kana = pyopenjtalk.g2p(say, kana=True)
    bad = [b for b in BAD if b in kana]
    if re.search(r"[A-Za-zＡ-Ｚａ-ｚ]", kana):
        bad.append("英字が残っている")
    # 小数点（例：199.9）の数と、読みの「テン」の数が合っているか
    dots = len(re.findall(r"\d[.点]\d", say))
    if dots and kana.count("テン") < dots:
        bad.append(f"小数点{dots}か所に対して「テン」が{kana.count('テン')}か所")
    return kana, bad


def yen_say(y):
    """円の金額を自然に読める形に（100円単位で丸める）。例：609400→「60万9400円」"""
    sign = "プラス" if y >= 0 else "マイナス"
    v = int(round(abs(y) / 100.0)) * 100
    man, rest = divmod(v, 10000)
    if man and rest:
        body = f"{man}万{rest}円"
    elif man:
        body = f"{man}万円"
    else:
        body = f"{rest}円"
    return sign + body


def yen_abs(y):
    """符号なしの金額（「約4万8900円」など）"""
    return yen_say(abs(y))[3:]
