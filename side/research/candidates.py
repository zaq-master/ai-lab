KEYS = ["free", "speed", "auto", "safe", "proof", "ceil"]
BASE = {"free": 1, "speed": 2, "auto": 2, "safe": 2, "proof": 2, "ceil": 1}


def score(c, w):
    vals = dict(zip(KEYS, c[3:9]))
    return sum(vals[k] * w[k] for k in KEYS) / sum(w.values())


def main(runs=100, seed=1):
    # AI副業の条件：AIが作業の半分以上を担えること（auto>=3）。人がやる作業（ポイ活等）は外す
    ok = [c for c in C if not c[9] and c[5] >= 3]
    rnd = random.Random(seed)
    hits = {c[0]: 0 for c in ok}
    for _ in range(runs):
        w = {k: BASE[k] * rnd.uniform(0.5, 1.5) for k in KEYS}  # 重みを±50%揺らす
        for c in sorted(ok, key=lambda c: -score(c, w))[:10]:
            hits[c[0]] += 1
    rows = sorted(ok, key=lambda c: (-hits[c[0]], -score(c, BASE)))
    print(f"除外 {100 - len(ok)}件（NG・AIが担えない） / 採点 {len(ok)}件 / 重みを変えて {runs}回")
    for c in rows[:20]:
        print(f"{c[0]:>3} {hits[c[0]]:>3}/{runs}  {score(c, BASE):.2f}  {c[1]}  ({c[10]})")


if __name__ == "__main__":
    main()
